"""Regenerate ``asta/markets/stock/idx_universe.py`` from a public IDX list.

idx.co.id is behind Cloudflare and answers 403 to plain HTTP clients, so the
scanner ships a static universe instead of scraping the exchange at startup.
The list below is seeded from the KSEI >1% register published by the
``fzn0x/idx`` project (``data/universe.csv``), which is refreshed past IPOs and
delistings. Re-run this script after a listing change:

    python scripts/fetch_idx_universe.py
    python scripts/fetch_idx_universe.py --csv /path/to/universe.csv
    python scripts/fetch_idx_universe.py --check

``--check`` only diffs the live CSV against the committed module and exits 1
when they disagree, so CI (or you) can spot drift without rewriting the file.
"""

from __future__ import annotations

import argparse
import io
import re
import sys
import urllib.request
from pathlib import Path
from typing import List, Optional, Tuple

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "src" / "asta" / "markets" / "stock" / "idx_universe.py"
SOURCE_URL = "https://raw.githubusercontent.com/fzn0x/idx/main/data/universe.csv"
CODE_PATTERN = re.compile(r"^[A-Z]{4}$")

HEADER = '''"""IDX (BEI) ticker universe shipped with the stock market.

Generated by ``scripts/fetch_idx_universe.py`` — edit that script, not this
file. Codes are bare IDX symbols (no ``.JK`` suffix); :func:`idx_symbols`
returns what the Yahoo-backed provider expects.

Listing changes are rare (a handful of IPOs and delistings per year), but a
stale entry only costs one wasted HTTP call: the provider answers "no usable
candles" and the analysis service logs it and moves on.
"""

from __future__ import annotations

from typing import List, Optional, Tuple

#: Where the codes came from, for the next refresh.
SOURCE = {source!r}
#: Date the upstream register was seeded.
SEEDED_AT = {seeded!r}

#: All issuers listed on the Indonesia Stock Exchange.
IDX_TICKERS: List[str] = [
{body}]


def idx_symbols(suffix: str = ".JK") -> List[str]:
    """Return provider-ready symbols (``BBCA`` -> ``BBCA.JK``)."""
    return [code + suffix for code in IDX_TICKERS]
'''


def read_codes(path: Optional[Path] = None, timeout: int = 30) -> Tuple[List[str], str]:
    if path is not None:
        text = path.read_text(encoding="utf-8")
    else:
        request = urllib.request.Request(SOURCE_URL, headers={"User-Agent": "asta-universe-fetch"})
        with urllib.request.urlopen(request, timeout=timeout) as response:
            text = response.read().decode("utf-8")

    codes: List[str] = []
    seeded = ""
    for line in io.StringIO(text):
        raw = line.strip()
        if not raw:
            continue
        if raw.startswith("#"):
            match = re.search(r"register of (\d{4}-\d{2}-\d{2})", raw)
            if match:
                seeded = match.group(1)
            continue
        symbol = raw.split(",")[0].strip().upper()
        if not CODE_PATTERN.match(symbol):
            continue
        codes.append(symbol)
    if not codes:
        raise SystemExit("no tickers parsed from the source list")
    # de-duplicate while keeping the source order
    seen = set()
    unique = [code for code in codes if not (code in seen or seen.add(code))]
    return unique, seeded


def render(codes: List[str], seeded: str) -> str:
    body = "\n".join(
        "    \"{}\",".format(code)
        for code in codes
    )
    return HEADER.format(
        source=SOURCE_URL,
        seeded=seeded or "unknown",
        body=body + "\n",
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--csv", type=Path, help="local universe.csv instead of the remote one")
    parser.add_argument("--check", action="store_true", help="exit 1 when the module is stale")
    args = parser.parse_args()

    codes, seeded = read_codes(args.csv)
    rendered = render(codes, seeded)

    if args.check:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current != rendered:
            print("universe is stale: {} tickers upstream".format(len(codes)))
            print("run: python scripts/fetch_idx_universe.py")
            return 1
        print("universe up to date: {} tickers".format(len(codes)))
        return 0

    TARGET.write_text(rendered, encoding="utf-8")
    print("wrote {} ({} tickers)".format(TARGET.relative_to(ROOT), len(codes)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
